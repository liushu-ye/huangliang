object Slogans {

    @Volatile
    private var lastIndex = -1

    /** 随机取一句，尽量不和上一句重复 */
    @Synchronized
    fun random(): String {
        if (SLOGANS.size < 2) return SLOGANS.first()
        var index = SLOGANS.indices.random()
        while (index == lastIndex) {
            index = SLOGANS.indices.random()
        }
        lastIndex = index
        return SLOGANS[index]
    }
}
